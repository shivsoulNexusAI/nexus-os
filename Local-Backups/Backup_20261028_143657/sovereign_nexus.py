def get_exact_broker_symbol(base_sym: str) -> str:

















  import MetaTrader5 as mt5

















  candidates = [base_sym, f"{base_sym}m", f"{base_sym}.s", f"{base_sym}c", f"{base_sym}raw"]

















  for s in candidates:

















    info = mt5.symbol_info(s)

















    if info is not None:

















      mt5.symbol_select(s, True)

















      return s

















  return base_sym



































def is_market_open(symbol: str) -> bool:

















  import MetaTrader5 as mt5

















  import time

















  real_sym = get_exact_broker_symbol(symbol)

















  tick = mt5.symbol_info_tick(real_sym)

















  if not tick:

















    return False

















  if (time.time() - tick.time) > 86400:

















    return False

















  info = mt5.symbol_info(real_sym)

















  return bool(info and info.trade_mode in [mt5.SYMBOL_TRADE_EXECUTION_MARKET, mt5.SYMBOL_TRADE_MODE_FULL])



































def calculate_confluence_edge(symbol: str) -> dict:

















  import MetaTrader5 as mt5

















  import numpy as np



































  real_sym = get_exact_broker_symbol(symbol)

















  tick = mt5.symbol_info_tick(real_sym)

















  spot_fallback = tick.bid if tick else 0.0



































  fallback_data = {

















    "score": 50.0,

















    "bias": "NEUTRAL",

















    "rsi": 50.0,

















    "spot": spot_fallback,

















    "status": "CONSOLIDATION"

















  }



































  rates = mt5.copy_rates_from_pos(real_sym, mt5.TIMEFRAME_M15, 0, 100)

















  if rates is None or len(rates) < 50:

















    return fallback_data



































  try:

















    closes = np.array([r["close"] for r in rates], dtype=float)

















    highs = np.array([r["high"] for r in rates], dtype=float)

















    lows = np.array([r["low"] for r in rates], dtype=float)



































    def calc_ema(arr, period):

















      alpha = 2.0 / (period + 1.0)

















      out = [arr[0]]

















      for p in arr[1:]:

















        out.append(alpha * p + (1.0 - alpha) * out[-1])

















      return np.array(out)



































    ema9 = calc_ema(closes, 9)

















    ema21 = calc_ema(closes, 21)

















    ema50 = calc_ema(closes, 50)



































    curr_c = closes[-1]

















    deltas = np.diff(closes[-15:])

















    gains = np.where(deltas > 0, deltas, 0.0)

















    losses = np.where(deltas < 0, -deltas, 0.0)

















    avg_g = np.mean(gains) if len(gains) > 0 else 0.0

















    avg_l = np.mean(losses) if len(losses) > 0 else 0.0001

















    rs = avg_g / (avg_l if avg_l != 0 else 0.0001)

















    rsi = 100.0 - (100.0 / (1.0 + rs))



































    bull_pts = 0.0

















    bear_pts = 0.0



































    if ema9[-1] > ema21[-1] > ema50[-1]:

















      bull_pts += 30.0

















    elif ema9[-1] < ema21[-1] < ema50[-1]:

















      bear_pts += 30.0

















    elif ema9[-1] > ema21[-1]:

















      bull_pts += 15.0

















    elif ema9[-1] < ema21[-1]:

















      bear_pts += 15.0



































    if rsi < 32.0:

















      bull_pts += 35.0

















    elif rsi > 68.0:

















      bear_pts += 35.0

















    elif 40.0 <= rsi <= 55.0 and bull_pts > 0:

















      bull_pts += 20.0

















    elif 45.0 <= rsi <= 60.0 and bear_pts > 0:

















      bear_pts += 20.0



































    if curr_c > np.max(highs[-10:-1]):

















      bull_pts += 25.0

















    elif curr_c < np.min(lows[-10:-1]):

















      bear_pts += 25.0



































    if bull_pts > bear_pts:

















      final_score = min(96.5, round(50.0 + (bull_pts * 0.48), 1))

















      bias = "BUY" if final_score >= 65.0 else "NEUTRAL"

















    elif bear_pts > bull_pts:

















      final_score = min(96.5, round(50.0 + (bear_pts * 0.48), 1))

















      bias = "SELL" if final_score >= 65.0 else "NEUTRAL"

















    else:

















      final_score = 50.0

















      bias = "NEUTRAL"



































    return {

















      "score": final_score,

















      "bias": bias,

















      "rsi": round(rsi, 1),

















      "spot": curr_c,

















      "status": "ACTIVE"

















    }

















  except Exception:

















    return fallback_data



































