def compile_eod_audit_data() -> dict:

















  import MetaTrader5 as mt5

















  from datetime import datetime, timezone



































  now_utc = datetime.now(timezone.utc)

















  start_of_day = datetime(now_utc.year, now_utc.month, now_utc.day, 0, 0, 0, tzinfo=timezone.utc)

















  

















  # Fetch closed deals since 00:00 UTC today

















  deals = mt5.history_deals_get(start_of_day, now_utc) or []

















  

















  realized_pnl = 0.0

















  wins = 0

















  losses = 0

















  gross_profit = 0.0

















  gross_loss = 0.0

















  closed_tickets = []



































  for d in deals:

















    # DEAL_ENTRY_OUT (1), DEAL_ENTRY_INOUT (2), DEAL_ENTRY_OUT_BY (3) are closed trades

















    if getattr(d, "entry", None) in [1, 2, 3] and d.profit != 0:

















      profit = float(d.profit) + float(d.swap) + float(d.commission)

















      realized_pnl += profit

















      closed_tickets.append(d.ticket)

















      if profit > 0:

















        wins += 1

















        gross_profit += profit

















      else:

















        losses += 1

















        gross_loss += abs(profit)



































  total_closed = wins + losses

















  win_rate = (wins / total_closed * 100.0) if total_closed > 0 else 0.0

















  profit_factor = (gross_profit / gross_loss) if gross_loss > 0 else (99.9 if gross_profit > 0 else 1.0)



































  # Fetch active portfolio snapshot

















  acc = get_mt5_snapshot()

















  eq = acc.get("equity", 0.0)

















  bal = acc.get("balance", 0.0)

















  fl_pnl = acc.get("floating_pnl", 0.0)

















  margin_used = acc.get("margin", 0.0)

















  margin_level = acc.get("margin_level", 0.0)

















  positions = acc.get("raw_positions", [])



































  # Drawdown metrics against High-Water Mark

















  hwm = max(eq, bal)

















  drawdown_pct = ((hwm - eq) / hwm * 100.0) if hwm > 0 else 0.0

















  circuit_headroom = max(0.0, 3.5 - drawdown_pct)



































  return {

















    "now_utc": now_utc.strftime("%Y-%m-%d %H:%M:%S UTC"),

















    "realized_pnl": realized_pnl,

















    "total_closed": total_closed,

















    "wins": wins,

















    "losses": losses,

















    "win_rate": win_rate,

















    "gross_profit": gross_profit,

















    "gross_loss": gross_loss,

















    "profit_factor": profit_factor,

















    "equity": eq,

















    "balance": bal,

















    "floating_pnl": fl_pnl,

















    "margin_used": margin_used,

















    "margin_level": margin_level,

















    "open_positions": positions,

















    "hwm": hwm,

















    "drawdown_pct": drawdown_pct,

















    "circuit_headroom": circuit_headroom,

















    "regime": EXECUTION_MODE

















  }



































