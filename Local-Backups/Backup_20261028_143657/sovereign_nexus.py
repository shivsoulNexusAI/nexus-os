def compute_m15_atr(symbol: str, period: int = 14) -> float:
    """Calculates live 14-period M15 Average True Range from MT5."""
    import MetaTrader5 as mt5
    rates = mt5.copy_rates_from_pos(symbol, mt5.TIMEFRAME_M15, 0, period + 5)
    if rates is None or len(rates) < period + 1:
        return 10.0 if "ETH" in symbol else (250.0 if "BTC" in symbol else 0.0015)
    highs = rates['high']
    lows = rates['low']
    closes = rates['close']
    tr_list = []
    for i in range(1, len(rates)):
        hl = highs[i] - lows[i]
        hpc = abs(highs[i] - closes[i - 1])
        lpc = abs(lows[i] - closes[i - 1])
        tr_list.append(max(hl, hpc, lpc))
    return float(np.mean(tr_list[-period:]))

