def calculate_dynamic_risk_lot(equity: float, symbol: str, spot: float, sl: float, risk_pct: float = 0.01):
    import MetaTrader5 as mt5
    info = mt5.symbol_info(symbol)
    vol_min = getattr(info, 'volume_min', 0.01) if info else 0.01
    vol_step = getattr(info, 'volume_step', 0.01) if info else 0.01
    vol_max = getattr(info, 'volume_max', 100.0) if info else 100.0
    contract_size = getattr(info, 'trade_contract_size', 1.0) if info else 1.0
    dist = abs(spot - sl) if sl else 0.0
    risk_cash = equity * risk_pct
    if dist <= 0:
        return {'lot': vol_min, 'cash': risk_cash, 'dist': dist}
    # Formula: Risk Cash / (Distance * Contract Size)
    raw_lot = risk_cash / (dist * contract_size)
    steps = round(raw_lot / vol_step)
    clamped = max(vol_min, min(vol_max, steps * vol_step))
    step_str = str(vol_step)
    digits = len(step_str.split('.')[1]) if '.' in step_str else 0
    final_lot = round(clamped, digits)
    return {'lot': final_lot, 'cash': risk_cash, 'dist': dist}

