def resolve_broker_symbol(symbol: str) -> str:

















  import MetaTrader5 as mt5

















  symbol = symbol.upper().strip()

















  candidates = [symbol, symbol + "m", symbol.replace("USD", "USDm")]

















  if symbol in ["BTC", "BTCUSD", "BTCUSDM"]:

















    candidates = ["BTCUSD", "BTCUSDm", "BTC"] + candidates

















  elif symbol in ["XAU", "GOLD", "XAUUSD"]:

















    candidates = ["XAUUSD", "XAUUSDm", "GOLD"] + candidates

















  elif symbol in ["ETH", "ETHUSD"]:

















    candidates = ["ETHUSD", "ETHUSDm"] + candidates



































  for s in candidates:

















    info = mt5.symbol_info(s)

















    if info is not None:

















      mt5.symbol_select(s, True)

















      return s

















  return symbol



































def execute_market_order(symbol: str, order_type_str: str, risk_pct: float = 1.0) -> tuple:

















  import MetaTrader5 as mt5

















  sym = resolve_broker_symbol(symbol)

















  sym_info = mt5.symbol_info(sym)

















  if sym_info is None:

















    return False, f"Symbol {symbol} (resolved as {sym}) not found on broker."



































  tick = mt5.symbol_info_tick(sym)

















  if not tick:

















    return False, f"No live price tick for {sym}."



































  lot = sym_info.volume_min

















  if "BTC" in sym:

















    lot = max(sym_info.volume_min, 0.05)



































  is_buy = "BUY" in order_type_str.upper()

















  order_type = mt5.ORDER_TYPE_BUY if is_buy else mt5.ORDER_TYPE_SELL

















  price = tick.ask if is_buy else tick.bid



































  pt = sym_info.point

















  dist = 300.0 * pt * 10 if "BTC" in sym else 50.0 * pt * 10

















  sl = price - dist if is_buy else price + dist

















  tp = price + (dist * 2) if is_buy else price - (dist * 2)



































  for filling in [mt5.ORDER_FILLING_IOC, mt5.ORDER_FILLING_RETURN, mt5.ORDER_FILLING_FOK]:

















    req = {

















      "action": mt5.TRADE_ACTION_DEAL,

















      "symbol": sym,

















      "volume": float(lot),

















      "type": order_type,

















      "price": float(price),

















      "sl": float(sl),

















      "tp": float(tp),

















      "deviation": 30,

















      "magic": 777001,

















      "comment": "Nexus Telegram Sim",

















      "type_time": mt5.ORDER_TIME_GTC,

















      "type_filling": filling,

















    }

















    res = mt5.order_send(req)

















    if res and res.retcode == mt5.TRADE_RETCODE_DONE:

















      return True, {

















        "ticket": res.order,

















        "symbol": sym,

















        "volume": res.volume,

















        "price": res.price,

















        "type": "BUY" if is_buy else "SELL"

















      }

















    elif res and res.retcode in [10030, 10027]:

















      continue

















    elif res:

















      return False, f"MT5 Error: {res.retcode} ({res.comment})"



































  last_err = mt5.last_error()

















  return False, f"Execution failed across all filling modes: {last_err}"



































