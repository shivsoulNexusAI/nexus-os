def detect_chart_directional_bias(image_path: str, caption_text: str = "") -> dict:

















  """

















  Analyzes caption semantics and chart image color dynamics to determine

















  whether the setup is bullish (BUY) or bearish (SELL).

















  """

















  txt = caption_text.upper() if caption_text else ""

















  

















  # 1. Semantic Caption Evaluation

















  sell_triggers = ["SELL", "SHORT", "BEAR", "PUT", "DOWN", "BREAKDOWN", "DUMP", "DROP"]

















  buy_triggers = ["BUY", "LONG", "BULL", "CALL", "UP", "BREAKOUT", "PUMP", "RALLY"]

















  

















  for word in sell_triggers:

















    if word in txt:

















      return {"bias": "SELL", "order_type": "SELL", "confidence": 95.0, "reason": f"Explicit semantic caption: {word}"}

















      

















  for word in buy_triggers:

















    if word in txt:

















      return {"bias": "BUY", "order_type": "BUY", "confidence": 95.0, "reason": f"Explicit semantic caption: {word}"}



































  # 2. Visual Pixel Color Delta Analysis

















  try:

















    from PIL import Image

















    with Image.open(image_path) as im:

















      w, h = im.size

















      # Crop the active price action region (center-right 50% width, 60% height)

















      chart_body = im.crop((int(w * 0.40), int(h * 0.20), int(w * 0.95), int(h * 0.85))).convert("RGB")

















      red_count = 0

















      green_count = 0

















      for x in range(0, chart_body.width, 4):

















        for y in range(0, chart_body.height, 4):

















          r, g, b = chart_body.getpixel((x, y))

















          # Red candle hues: strong red, subdued green/blue

















          if r > 160 and g < 90 and b < 90:

















            red_count += 1

















          # Green candle hues: strong green, subdued red

















          elif g > 150 and r < 100 and b < 120:

















            green_count += 1

















            

















      if red_count > green_count * 1.25 and red_count > 30:

















        return {"bias": "SELL", "order_type": "SELL", "confidence": 88.0, "reason": f"Bearish Order Flow (Red: {red_count} > Green: {green_count})"}

















  except Exception:

















    pass



































  return {"bias": "BUY", "order_type": "BUY", "confidence": 85.0, "reason": "Default Accumulation Bias"}



































