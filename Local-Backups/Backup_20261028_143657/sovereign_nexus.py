def execute_mt5_order(symbol='BTCUSD', volume=0.01, order_type='BUY', sl=None, tp=None, comment='Quant Nexus'):
    import MetaTrader5 as mt5
    if not mt5.initialize():
        return False, 'MT5 bridge offline'
    info = mt5.symbol_info(symbol)
    if not info:
        return False, f'Unknown symbol {symbol}'
    if not info.visible:
        mt5.symbol_select(symbol, True)
    vol_min = getattr(info, 'volume_min', 0.01)
    vol_step = getattr(info, 'volume_step', 0.01)
    vol_max = getattr(info, 'volume_max', 100.0)
    steps = round(float(volume) / vol_step)
    norm_vol = max(vol_min, min(vol_max, steps * vol_step))
    step_str = str(vol_step)
    vol_digits = len(step_str.split('.')[1]) if '.' in step_str else 0
    norm_vol = round(norm_vol, vol_digits)
    filling = mt5.ORDER_FILLING_IOC if (info.filling_mode & 2) else (mt5.ORDER_FILLING_FOK if (info.filling_mode & 1) else mt5.ORDER_FILLING_RETURN)
    tick = mt5.symbol_info_tick(symbol)
    if not tick:
        return False, f'No tick for {symbol}'
    ot = mt5.ORDER_TYPE_BUY if str(order_type).upper() == 'BUY' else mt5.ORDER_TYPE_SELL
    price = tick.ask if ot == mt5.ORDER_TYPE_BUY else tick.bid
    digits = getattr(info, 'digits', 2)
    req = {
        'action': mt5.TRADE_ACTION_DEAL,
        'symbol': symbol,
        'volume': norm_vol,
        'type': ot,
        'price': price,
        'deviation': 30,
        'magic': 999777,
        'comment': str(comment)[:31],
        'type_time': mt5.ORDER_TIME_GTC,
        'type_filling': filling,
    }
    if sl is not None and sl > 0:
        req['sl'] = round(float(sl), digits)
    if tp is not None and tp > 0:
        req['tp'] = round(float(tp), digits)
    res = mt5.order_send(req)
    if res and res.retcode == mt5.TRADE_RETCODE_DONE:
        return True, res.order
    retcode = getattr(res, 'retcode', 'Unknown')
    comment_err = getattr(res, 'comment', '')
    return False, f'Rejected (code {retcode}: {comment_err})'

